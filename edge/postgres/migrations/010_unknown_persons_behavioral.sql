-- Week 5: Behavioral Analytics - Unknown Persons & Activity Tracking
-- Auto-create unknown persons, track activities, generate behavior reports
-- Created: 2026-11-08

-- ============================================================================
-- UNKNOWN PERSONS TABLE
-- ============================================================================
-- Auto-created when unidentified person is detected
-- Allows tracking same unknown across cameras until manually linked

CREATE TABLE IF NOT EXISTS unknown_persons (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    unknown_id VARCHAR(50) UNIQUE NOT NULL,  -- 'unknown_001', 'unknown_002', etc.
    face_embedding VECTOR(512) NOT NULL,
    first_seen TIMESTAMP NOT NULL DEFAULT NOW(),
    last_seen TIMESTAMP NOT NULL DEFAULT NOW(),
    detection_count INTEGER DEFAULT 1,
    sample_photo_url TEXT,  -- First or best quality photo

    -- Manual linking (admin action)
    linked_to_person_id VARCHAR(50),  -- NULL until manually linked to real person
    linked_at TIMESTAMP,
    linked_by VARCHAR(100),  -- Admin who performed linking

    notes TEXT,
    active BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMP DEFAULT NOW()
);

-- Index for face similarity search
CREATE INDEX IF NOT EXISTS idx_unknown_persons_face
ON unknown_persons USING ivfflat (face_embedding vector_cosine_ops)
WITH (lists = 50);

-- Index for finding unlinked unknowns
CREATE INDEX IF NOT EXISTS idx_unknown_persons_unlinked
ON unknown_persons (active, linked_to_person_id)
WHERE linked_to_person_id IS NULL;

-- Index for last seen (recent unknowns first)
CREATE INDEX IF NOT EXISTS idx_unknown_persons_last_seen
ON unknown_persons (last_seen DESC);


-- ============================================================================
-- PERSON DETECTIONS TABLE
-- ============================================================================
-- Every detection event from stream processor
-- Links to enrolled_persons OR unknown_persons

CREATE TABLE IF NOT EXISTS person_detections (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    person_id VARCHAR(50) NOT NULL,  -- Can be 'adam_w' or 'unknown_001'
    camera_id VARCHAR(50) NOT NULL,
    zone_name VARCHAR(50),  -- Derived from camera location
    detected_at TIMESTAMP NOT NULL DEFAULT NOW(),
    confidence FLOAT NOT NULL,  -- Face recognition confidence
    bbox JSONB,  -- Bounding box {x1, y1, x2, y2, width, height}

    -- Activity classification (Week 5)
    activity VARCHAR(50),  -- 'playing', 'eating', 'crying', 'sitting', etc.
    activity_confidence FLOAT,

    -- Optional frame reference
    frame_url TEXT,  -- Link to frame image in storage

    created_at TIMESTAMP DEFAULT NOW()
);

-- Indexes for person_detections
CREATE INDEX IF NOT EXISTS idx_person_detections_person_time
ON person_detections (person_id, detected_at DESC);

CREATE INDEX IF NOT EXISTS idx_person_detections_camera_time
ON person_detections (camera_id, detected_at DESC);

CREATE INDEX IF NOT EXISTS idx_person_detections_activity
ON person_detections (activity, detected_at DESC)
WHERE activity IS NOT NULL;

-- For date range queries
CREATE INDEX IF NOT EXISTS idx_person_detections_date
ON person_detections (DATE(detected_at), person_id);


-- ============================================================================
-- ACTIVITY EVENTS TABLE
-- ============================================================================
-- Aggregated activity sessions (multiple detections of same activity)
-- e.g., "Playing from 10:15-10:45 (30 min)"

CREATE TABLE IF NOT EXISTS activity_events (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    person_id VARCHAR(50) NOT NULL,
    camera_id VARCHAR(50) NOT NULL,
    zone_name VARCHAR(50),

    activity VARCHAR(50) NOT NULL,
    started_at TIMESTAMP NOT NULL,
    ended_at TIMESTAMP,  -- NULL if ongoing
    duration_seconds INTEGER,  -- Auto-calculated on end
    confidence FLOAT,  -- Average confidence during activity

    detection_count INTEGER DEFAULT 1,  -- Number of detections aggregated

    created_at TIMESTAMP DEFAULT NOW()
);

-- Indexes for activity_events
CREATE INDEX IF NOT EXISTS idx_activity_events_person_time
ON activity_events (person_id, started_at DESC);

CREATE INDEX IF NOT EXISTS idx_activity_events_activity
ON activity_events (activity, started_at DESC);

CREATE INDEX IF NOT EXISTS idx_activity_events_date
ON activity_events (DATE(started_at), person_id);


