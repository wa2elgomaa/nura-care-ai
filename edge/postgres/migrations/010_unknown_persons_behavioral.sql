-- Function to get next unknown ID
CREATE OR REPLACE FUNCTION get_next_unknown_id()
RETURNS VARCHAR AS $$
DECLARE
    next_num INTEGER;
BEGIN
    SELECT COALESCE(MAX(
        CAST(SUBSTRING(unknown_id FROM 'unknown_([0-9]+)') AS INTEGER)
    ), 0) + 1
    INTO next_num
    FROM unknown_persons;

    RETURN 'unknown_' || LPAD(next_num::TEXT, 3, '0');
END;
$$ LANGUAGE plpgsql;

