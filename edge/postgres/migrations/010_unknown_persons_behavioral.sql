-- View: Unknown persons summary
CREATE OR REPLACE VIEW unknown_persons_summary AS
SELECT
    unknown_id,
    first_seen,
    last_seen,
    detection_count,
    linked_to_person_id,
    CASE
        WHEN linked_to_person_id IS NOT NULL THEN 'linked'
        WHEN last_seen > NOW() - INTERVAL '24 hours' THEN 'recent'
        ELSE 'old'
    END as status
FROM unknown_persons
WHERE active = true
ORDER BY last_seen DESC;

-- View: Daily activity summary per person
CREATE OR REPLACE VIEW daily_activity_summary AS
SELECT
    person_id,
    DATE(detected_at) as date,
    activity,
    COUNT(*) as detection_count,
    ROUND(AVG(activity_confidence)::numeric, 2) as avg_confidence
FROM person_detections
WHERE activity IS NOT NULL
GROUP BY person_id, DATE(detected_at), activity
ORDER BY date DESC, person_id, detection_count DESC;

-- View: Person activity distribution (all time)
CREATE OR REPLACE VIEW person_activity_distribution AS
SELECT
    person_id,
    activity,
    COUNT(*) as count,
    ROUND((COUNT(*)::NUMERIC / SUM(COUNT(*)) OVER (PARTITION BY person_id) * 100), 1) as percentage
FROM person_detections
WHERE activity IS NOT NULL
GROUP BY person_id, activity
ORDER BY person_id, count DESC;


